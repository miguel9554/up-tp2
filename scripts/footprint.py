#!/usr/bin/env python3
"""Generate the footprint of a design: die area and I/O pin locations.

Usage: footprint.py <design> <area> <aspect_ratio>

<area> is the die area in µm² and <aspect_ratio> its height / width. The I/O
pins are the ports of the imported TP1 netlist (designs/<design>/tp1/), spread
uniformly around the die edge in declaration order (so buses stay together),
counterclockwise from the lower-left corner: south, east, north, west. Each
edge gets a number of pins proportional to its length.

Writes:
    designs/<design>/footprint.def   DIEAREA + PINS (FP_DEF_TEMPLATE)
    designs/<design>/config.json     DIE_AREA updated to match
"""
import json
import math
import re
import sys
from pathlib import Path

DBU = 1000  # DEF database units per µm

# sky130 routing tracks (FP_TRACKS_INFO of the PDK): pins on the south/north
# edges are on met2 (vertical), on the east/west edges on met3 (horizontal).
# Pin shapes are the minimum squares OpenROAD's pin placer uses.
V_LAYER, V_OFFSET, V_PITCH, V_HALF = "met2", 0.23, 0.46, 0.14
H_LAYER, H_OFFSET, H_PITCH, H_HALF = "met3", 0.34, 0.68, 0.30

CORNER_KEEPOUT = 20  # µm without pins at each end of an edge

PORT_RE = re.compile(r"^\s*(input|output|inout)\s*(?:\[(\d+):(\d+)\])?\s*([\w$]+)\s*;", re.M)


def ports(netlist: Path):
    """Port bits of the netlist, in declaration order: [(name, direction)]."""
    bits = []
    for direction, msb, lsb, name in PORT_RE.findall(netlist.read_text()):
        if msb:
            lo, hi = sorted((int(msb), int(lsb)))
            bits += [(f"{name}[{i}]", direction) for i in range(lo, hi + 1)]
        else:
            bits.append((name, direction))
    return bits


def dbu(um: float) -> int:
    return round(um * DBU)


def on_track(pos: float, offset: float, pitch: float) -> float:
    return offset + round((pos - offset) / pitch) * pitch


def spread(n: int, length: float, offset: float, pitch: float):
    """n positions evenly spaced along an edge of the given length, on tracks."""
    usable = length - 2 * CORNER_KEEPOUT
    pos = [on_track(CORNER_KEEPOUT + (i + 0.5) * usable / n, offset, pitch) for i in range(n)]
    if len(set(pos)) != n:
        sys.exit(f"error: {n} pins do not fit on a {length:.0f} µm edge: use a larger area")
    return pos


def main():
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    design = sys.argv[1]
    area, aspect = float(sys.argv[2]), float(sys.argv[3])
    if area <= 0 or aspect <= 0:
        sys.exit("error: area and aspect ratio must be positive")

    design_dir = Path("designs") / design
    config_file = design_dir / "config.json"
    config = json.loads(config_file.read_text())
    name = config["DESIGN_NAME"]
    netlist = design_dir / "tp1" / f"{name}.nl.v"
    if not netlist.is_file():
        sys.exit(f"error: {netlist} not found: import the TP1 netlist first (make import-tp1)")
    pins = ports(netlist)

    # Whole µm, so that macro coordinates are easy to reason about.
    w = round(math.sqrt(area / aspect))
    h = round(w * aspect)

    # Pins per edge, proportional to its length (south, east, north, west).
    lengths = [w, h, w, h]
    counts = [round(len(pins) * sum(lengths[:i + 1]) / sum(lengths)) for i in range(4)]
    counts = [b - a for a, b in zip([0] + counts, counts)]

    # Counterclockwise: along the south edge left to right, the east one bottom
    # to top, the north one right to left and the west one top to bottom.
    placed = []  # (name, direction, layer, half size, x, y)
    rest = iter(pins)
    for edge, n in zip("SENW", counts):
        if edge in "SN":
            xs = spread(n, w, V_OFFSET, V_PITCH)
            xs = xs if edge == "S" else xs[::-1]
            y = V_HALF if edge == "S" else h - V_HALF
            placed += [(*next(rest), V_LAYER, V_HALF, x, y) for x in xs]
        else:
            ys = spread(n, h, H_OFFSET, H_PITCH)
            ys = ys if edge == "E" else ys[::-1]
            x = w - H_HALF if edge == "E" else H_HALF
            placed += [(*next(rest), H_LAYER, H_HALF, x, y) for y in ys]

    lines = [
        f"# Footprint of {name}: {w} x {h} µm (area {area:g} µm², aspect ratio {aspect:g}).",
        f"# Generated by scripts/footprint.py from {netlist}.",
        "VERSION 5.8 ;",
        'DIVIDERCHAR "/" ;',
        'BUSBITCHARS "[]" ;',
        f"DESIGN {name} ;",
        f"UNITS DISTANCE MICRONS {DBU} ;",
        f"DIEAREA ( 0 0 ) ( {dbu(w)} {dbu(h)} ) ;",
        f"PINS {len(placed)} ;",
    ]
    for pin, direction, layer, half, x, y in placed:
        lines += [
            f"    - {pin} + NET {pin} + DIRECTION {direction.upper()} + USE SIGNAL",
            "      + PORT",
            f"        + LAYER {layer} ( {-dbu(half)} {-dbu(half)} ) ( {dbu(half)} {dbu(half)} )",
            f"        + PLACED ( {dbu(x)} {dbu(y)} ) N ;",
        ]
    lines += ["END PINS", "END DESIGN", ""]
    (design_dir / "footprint.def").write_text("\n".join(lines))

    config["DIE_AREA"] = [0, 0, w, h]
    text = json.dumps(config, indent=4, ensure_ascii=False)
    text = re.sub(r'"DIE_AREA": \[[^\]]*\]', f'"DIE_AREA": {config["DIE_AREA"]}', text)
    config_file.write_text(text + "\n")

    print(f"Footprint of {name}: die {w} x {h} µm ({w * h} µm²), "
          f"{len(placed)} pins (S {counts[0]}, E {counts[1]}, N {counts[2]}, W {counts[3]}).")
    print(f"Written {design_dir / 'footprint.def'}; DIE_AREA in {config_file} set to {config['DIE_AREA']}.")


if __name__ == "__main__":
    main()
